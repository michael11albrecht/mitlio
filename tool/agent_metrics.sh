#!/usr/bin/env bash
# Agent pipeline metrics (plan §6.7, P1-T11): one row per merged PR.
#
#   tool/agent_metrics.sh [--since YYYY-MM-DD] [--until YYYY-MM-DD] [--write]
#   tool/agent_metrics.sh --input FIXTURE.json      # offline (tests)
#
# Needs bash, gh (authenticated) and jq. --write regenerates docs/agent-metrics.md.
# FIXTURE.json is an array of {pr, runs, inline}: the recorded output of
# `gh pr list --state merged --json ...`, `gh run list --branch B --json ...`
# and the inline review comment count of `gh api repos/R/pulls/N/comments`.
set -euo pipefail
cd "$(dirname "$0")/.."

since="" until="" write=0 input=""
while [ $# -gt 0 ]; do
  case "$1" in
    --since) since="${2:?}"; shift 2 ;;
    --until) until="${2:?}"; shift 2 ;;
    --write) write=1; shift ;;
    --input) input="${2:?}"; shift 2 ;;
    -h | --help) sed -n '2,10p' "$0"; exit 0 ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done

fetch() {
  local repo nums pr n branch runs inline
  repo="$(gh repo view --json nameWithOwner -q .nameWithOwner)"
  # Numbers first, then one `gh pr view` each: a single big `gh pr list` query
  # with commits+author exceeds GitHub's GraphQL node limit.
  nums="$(gh pr list --state merged --limit 1000 --json number -q '.[].number')"
  for n in $nums; do
    pr="$(gh pr view "$n" \
      --json number,title,body,headRefName,author,commits,createdAt,mergedAt)"
    branch="$(jq -r .headRefName <<<"$pr")"
    runs="$(gh run list --branch "$branch" --limit 100 \
      --json conclusion,createdAt,event,headSha,workflowName)"
    inline="$(gh api "repos/$repo/pulls/$n/comments" --paginate --jq length | jq -s 'add // 0')"
    jq -c -n --argjson pr "$pr" --argjson runs "$runs" --argjson inline "$inline" \
      '{pr: $pr, runs: $runs, inline: $inline}'
  done | jq -s '.'
}

if [ -n "$input" ]; then
  data="$(cat "$input")"
else
  data="$(fetch)" || { echo "fetching from GitHub failed" >&2; exit 1; }
fi

report="$(jq -r --arg since "$since" --arg until "$until" '
  def median: sort | if length == 0 then null
    else (length / 2 | floor) as $i
      | if length % 2 == 1 then .[$i] else (.[$i - 1] + .[$i]) / 2 end end;
  def r1: if . == null then "-" else (. * 10 | round) / 10 | tostring end;
  [ .[]
    | select(($since == "") or (.pr.mergedAt[0:10] >= $since))
    | select(($until == "") or (.pr.mergedAt[0:10] <= $until))
    | .pr as $pr
    # CI = workflow "ci" on pull_request, oldest first, cancelled runs ignored.
    | ([ .runs[] | select(.workflowName == "ci" and .event == "pull_request"
          and (.conclusion == "success" or .conclusion == "failure")) ]
        | sort_by(.createdAt)) as $ci
    | {
        number: $pr.number,
        title: ($pr.title | gsub("\\|"; "/")),
        task: ((($pr.body // "") | capture("Task ID: *(?<t>[A-Za-z0-9-]+)") | .t) // "-"),
        branch: $pr.headRefName,
        kind: (if ($pr.author.is_bot // false) or ($pr.author.login | startswith("app/"))
               then "app"
               elif ($pr.headRefName | startswith("agent/")) then "local-agent"
               else "manual" end),
        commits: ($pr.commits | length),
        ci_runs: ($ci | length),
        fix_rounds: (if ($ci | length) == 0 then null
                     else [ $ci[] | select(.conclusion == "failure") ] | length end),
        first_green: (if ($ci | length) == 0 then null else $ci[0].conclusion == "success" end),
        inline: .inline,
        hours: ((($pr.mergedAt | fromdateiso8601) - ($pr.createdAt | fromdateiso8601)) / 3600)
      } ] as $rows
  | ($rows | map(select(.first_green != null))) as $ci_rows
  | "| PR | Title | Task | Branch | Author | Commits | CI runs | CI-fix rounds | First-push green | Inline review comments | Open to merge (h) | Cost |",
    "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ($rows[] | "| #\(.number) | \(.title) | \(.task) | `\(.branch)` | \(.kind) | \(.commits) | \(.ci_runs) | \(.fix_rounds // "-") | \(if .first_green == null then "-" elif .first_green then "yes" else "no" end) | \(.inline) | \(.hours | r1) | |"),
    "| **Summary** | **\($rows | length) PRs** | | | | \($rows | map(.commits) | add // 0) | | median \($ci_rows | map(.fix_rounds) | median | r1) | \(if ($ci_rows | length) == 0 then "-" else "\(($ci_rows | map(select(.first_green)) | length) * 100 / ($ci_rows | length) | round)%" end) | \($rows | map(.inline) | add // 0) | median \($rows | map(.hours) | median | r1) | |"
' <<<"$data")"

if [ "$write" -eq 1 ]; then
  {
    cat <<'HDR'
# Agent metrics

Generated by `make agent-metrics` (`tool/agent_metrics.sh --write`) from merged PRs. Do not edit by hand.
Purpose: an honest, cheap record of how the agentic pipeline performs (plan §6.7). Reviewed monthly (ADR-18).

| Column | Meaning |
|---|---|
| Task | `Task ID:` from the PR body |
| Author | `app` = GitHub App / bot PR; `local-agent` = `agent/*` branch pushed from the local orchestrator; `manual` = any other branch |
| Commits | commits in the PR |
| CI runs | finished `ci` runs (pull_request event) on the head branch, cancelled runs ignored |
| CI-fix rounds | failed `ci` runs, i.e. rounds needed before the final green |
| First-push green | the first finished `ci` run succeeded |
| Inline review comments | inline review comments on the PR (Copilot / agent review / human) |
| Open to merge (h) | hours from PR creation to merge |
| Cost | intentionally blank: GitHub does not expose it and implementation runs on a subscription token with no marginal cost (plan §6.8); fill by hand if an API-billed run is ever used |

Summary row: first-push green is the share of PRs that still have CI run history; "-" in CI columns means run history is no longer available.
The Summary row's CI-fix rounds and Open to merge cells are medians.

HDR
    printf '%s\n' "$report"
  } > docs/agent-metrics.md
  echo "wrote docs/agent-metrics.md" >&2
else
  printf '%s\n' "$report"
fi
